using System.Net.Sockets;
using MailKit;
using MailKit.Net.Smtp;
using MailKit.Security;
using MimeKit;
using OmniAI.Application.Notifications;
using OmniAI.Domain.Notifications;

namespace OmniAI.Infrastructure.Notifications.Email;

/// <summary>
/// Sends operational email over SMTP, with MailKit.
/// </summary>
/// <remarks>
/// <para>
/// <strong>What happened is reported in two halves.</strong> Everything up to and
/// including signing in hands nothing over, so a failure there is
/// <see cref="OperationalEmailOutcome.NotSent"/> and may be retried. Once the
/// message is being transmitted, a refusal the server states — sender, recipient
/// or message not accepted — is a definite <see cref="OperationalEmailOutcome.Rejected"/>;
/// anything else, a dropped connection or a timeout, is
/// <see cref="OperationalEmailOutcome.Ambiguous"/>, because the server may already
/// have accepted it.
/// </para>
/// <para>
/// <strong>Nothing is logged here.</strong> No protocol logger is attached, so no
/// SMTP transcript — with its addresses, credentials and content — is written
/// anywhere. Exceptions are reduced to stable codes before they leave.
/// </para>
/// <para>
/// <strong>Addressing is the server's.</strong> The sender is configuration; the
/// recipient is the member's account address; the subject is a constant. No header
/// is built from workspace-authored text, so no line break in a workspace name can
/// add a <c>Bcc:</c>.
/// </para>
/// </remarks>
internal sealed class SmtpOperationalEmailSender(OperationalEmailOptions options) : IOperationalEmailSender
{
    private readonly OperationalEmailOptions _options = options ?? throw new ArgumentNullException(nameof(options));

    public bool IsConfigured => true;

    public async Task<OperationalEmailResult> SendAsync(
        OperationalEmailMessage message,
        CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(message);

        MimeMessage mime = Build(message);

        using SmtpClient client = new()
        {
            Timeout = (int)_options.Smtp.Timeout.TotalMilliseconds,
        };

        try
        {
            try
            {
                await client
                    .ConnectAsync(_options.Smtp.Host!.Trim(), _options.Smtp.Port, SocketOptions(), cancellationToken)
                    .ConfigureAwait(false);

                if (!string.IsNullOrEmpty(_options.Smtp.Username))
                {
                    await client
                        .AuthenticateAsync(_options.Smtp.Username, _options.Smtp.Password ?? string.Empty, cancellationToken)
                        .ConfigureAwait(false);
                }
            }
            catch (AuthenticationException)
            {
                return new(OperationalEmailOutcome.NotSent, NotificationEmailFailures.AuthenticationFailed);
            }
            catch (Exception failure) when (IsConnectFailure(failure))
            {
                return new(OperationalEmailOutcome.NotSent, NotificationEmailFailures.ConnectFailed);
            }

            try
            {
                await client.SendAsync(mime, cancellationToken).ConfigureAwait(false);
            }
            catch (SmtpCommandException refused) when (refused.ErrorCode is SmtpErrorCode.SenderNotAccepted
                or SmtpErrorCode.RecipientNotAccepted
                or SmtpErrorCode.MessageNotAccepted)
            {
                // The server said no, in words. Nothing was delivered and repeating
                // the same message will be refused the same way.
                return new(OperationalEmailOutcome.Rejected, NotificationEmailFailures.Rejected);
            }
#pragma warning disable CA1031 // Every other failure mid-send is ambiguous, whatever its type.
            catch (Exception)
#pragma warning restore CA1031
            {
                return new(OperationalEmailOutcome.Ambiguous, NotificationEmailFailures.Ambiguous);
            }

            return OperationalEmailResult.Delivered;
        }
        finally
        {
            await QuitAsync(client).ConfigureAwait(false);
        }
    }

    /// <summary>
    /// The message: fixed headers, a text part and an HTML part, and no attachment.
    /// </summary>
    internal MimeMessage Build(OperationalEmailMessage message)
    {
        MimeMessage mime = new();

        mime.From.Add(new MailboxAddress(_options.Smtp.FromName, _options.Smtp.FromAddress!.Trim()));
        mime.To.Add(new MailboxAddress(string.Empty, message.To.Value));
        mime.Subject = message.Subject;
        mime.Date = DateTimeOffset.UtcNow;

        // RFC 3834: generated by a system, not by a person. Auto-responders stay quiet.
        mime.Headers.Add("Auto-Submitted", "auto-generated");

        mime.Body = new BodyBuilder
        {
            TextBody = message.TextBody,
            HtmlBody = message.HtmlBody,
        }.ToMessageBody();

        return mime;
    }

    private SecureSocketOptions SocketOptions() => _options.Smtp.Security switch
    {
        SmtpSecurity.SslOnConnect => SecureSocketOptions.SslOnConnect,
        SmtpSecurity.None => SecureSocketOptions.None,
        _ => SecureSocketOptions.StartTls,
    };

    private static bool IsConnectFailure(Exception failure) =>
        failure is SocketException
            or IOException
            or TimeoutException
            or OperationCanceledException
            or SslHandshakeException
            or SmtpProtocolException
            or SmtpCommandException
            or NotSupportedException
            or ServiceNotConnectedException;

    private static async Task QuitAsync(SmtpClient client)
    {
        if (!client.IsConnected)
        {
            return;
        }

        try
        {
            using CancellationTokenSource bounded = new(TimeSpan.FromSeconds(5));

            await client.DisconnectAsync(quit: true, bounded.Token).ConfigureAwait(false);
        }
#pragma warning disable CA1031 // Closing a finished conversation cannot change what it achieved.
        catch (Exception)
#pragma warning restore CA1031
        {
        }
    }
}

/// <summary>
/// Development pointed at a real SMTP server, and nobody opted in.
/// </summary>
/// <remarks>
/// <para>
/// The same philosophy as the WhatsApp and OpenAI guards: in Development, a
/// non-loopback host without <c>OMNIAI_LIVE_EMAIL=1</c> gets this sender, which has
/// no network code at all. Every email is recorded as failed with
/// <c>live_email_disabled</c>; nothing leaves the machine and no stranger's inbox
/// receives a test.
/// </para>
/// <para>
/// A loopback sink needs no opt-in. Production never uses this class.
/// </para>
/// </remarks>
internal sealed class WithheldOperationalEmailSender : IOperationalEmailSender
{
    public bool IsConfigured => true;

    public Task<OperationalEmailResult> SendAsync(
        OperationalEmailMessage message,
        CancellationToken cancellationToken = default) =>
        Task.FromResult(new OperationalEmailResult(OperationalEmailOutcome.Rejected, NotificationEmailFailures.LiveEmailDisabled));
}

/// <summary>No SMTP host is configured, so no email is ever queued.</summary>
internal sealed class UnconfiguredOperationalEmailSender : IOperationalEmailSender
{
    public bool IsConfigured => false;

    public Task<OperationalEmailResult> SendAsync(
        OperationalEmailMessage message,
        CancellationToken cancellationToken = default) =>
        Task.FromResult(new OperationalEmailResult(OperationalEmailOutcome.NotSent, NotificationEmailFailures.EmailNotConfigured));
}
