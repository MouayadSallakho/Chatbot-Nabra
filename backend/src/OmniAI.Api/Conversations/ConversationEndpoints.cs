using OmniAI.Api.Http;
using OmniAI.Api.Security;
using OmniAI.Application.Concurrency;
using OmniAI.Application.Conversations;
using OmniAI.Application.Conversations.Persistence;
using OmniAI.Domain.Conversations;

namespace OmniAI.Api.Conversations;

/// <summary>
/// A member of the workspace, as a conversation screen names one.
/// </summary>
/// <remarks>
/// Published on the admin API only. Every public transport builds its own view
/// type, and none of them has a field this could be assigned to — which is what
/// stops an employee's email reaching a customer by an oversight rather than by a
/// rule somebody has to remember.
/// </remarks>
public sealed record WorkspaceMemberResponse(Guid UserId, string Email);

/// <summary>One conversation, in a workspace's list.</summary>
public sealed record ConversationSummaryResponse(
    Guid Id,
    string Channel,
    string Status,
    string Handling,
    DateTimeOffset StartedAt,
    DateTimeOffset LastActivityAt,
    string? AgentName,
    int MessageCount,
    string? LastMessagePreview,
    string? LastMessageSender,
    WorkspaceMemberResponse? AssignedTo);

/// <summary>A page of conversations.</summary>
public sealed record ConversationPageResponse(
    IReadOnlyList<ConversationSummaryResponse> Items,
    int Page,
    int PageSize,
    int Total);

/// <summary>One conversation's detail.</summary>
public sealed record ConversationDetailResponse(
    Guid Id,
    string Channel,
    string Status,
    string Handling,
    DateTimeOffset StartedAt,
    DateTimeOffset LastActivityAt,
    string? AgentName,
    int MessageCount,
    WorkspaceMemberResponse? AssignedTo);

/// <summary>A reply written by a person.</summary>
/// <param name="ClientMessageId">
/// Generated by the composer before the request leaves the browser. Sending the
/// same one twice stores one message.
/// </param>
public sealed record ReplyToConversationRequest(string? ClientMessageId, string? Text);

/// <summary>Who to route a conversation to, or nobody.</summary>
public sealed record AssignConversationRequest(Guid? Member);

/// <summary>One message in a transcript.</summary>
/// <remarks>
/// Carries the ingestion sequence because it is the pagination cursor. It is not
/// a timestamp and must not be rendered as one; it is the platform's ordering,
/// which is what makes paging a transcript stable while it is still being added
/// to.
/// </remarks>
/// <param name="SentBy">
/// For a reply a person wrote, who wrote it. Null for every other sender.
/// </param>
public sealed record TranscriptMessageResponse(
    Guid Id,
    string Sender,
    string Text,
    DateTimeOffset SentAt,
    long Sequence,
    WorkspaceMemberResponse? SentBy);

/// <summary>A page of a transcript.</summary>
public sealed record TranscriptPageResponse(
    IReadOnlyList<TranscriptMessageResponse> Items,
    long? NextCursor);

/// <summary>
/// Reading a workspace's conversations.
/// </summary>
/// <remarks>
/// <strong>Read-only, and every route needs <c>conversations.view</c>.</strong>
/// There is no reply, no assignment and no delete, because none of those exist
/// yet — and an endpoint that accepted a reply would need a human-agent identity
/// the platform has not designed.
/// <para>
/// <strong>An anonymous visitor's credential is worth nothing here.</strong>
/// These routes require an authenticated session and a membership decision; the
/// conversation cookie is not read, is not sent to this path, and could not
/// satisfy the authorizer if it were.
/// </para>
/// </remarks>
internal static class ConversationEndpoints
{
    public static IEndpointRouteBuilder MapConversationEndpoints(this IEndpointRouteBuilder endpoints)
    {
        ArgumentNullException.ThrowIfNull(endpoints);

        RouteGroupBuilder workspace = endpoints
            .MapGroup("/api/tenants/{tenantId:guid}/conversations")
            .WithTags("Conversations")
            .RequireAuthorization()
            .AddEndpointFilter<AntiforgeryEndpointFilter>();

        workspace.MapGet("/", ListAsync)
            .WithName("ListTenantConversations");

        workspace.MapGet("/{conversationId:guid}", GetAsync)
            .WithName("GetTenantConversationById");

        workspace.MapGet("/{conversationId:guid}/messages", ListMessagesAsync)
            .WithName("ListTenantConversationMessages");

        // The operational routes. All four are unsafe writes on the same
        // authenticated, antiforgery-protected group as everything else here:
        // there is no public entry to any of them, and a visitor's conversation
        // credential opens none of them.
        workspace.MapPost("/{conversationId:guid}/take-over", TakeOverAsync)
            .WithName("TakeOverTenantConversation");

        workspace.MapPost("/{conversationId:guid}/return-to-ai", ReturnToAiAsync)
            .WithName("ReturnTenantConversationToAi");

        workspace.MapPut("/{conversationId:guid}/assignment", AssignAsync)
            .WithName("AssignTenantConversation");

        workspace.MapPost("/{conversationId:guid}/messages", ReplyAsync)
            .WithName("ReplyToTenantConversation");

        workspace.MapGet("/assignees", ListAssigneesAsync)
            .WithName("ListTenantConversationAssignees");

        return endpoints;
    }

    /// <summary><c>GET /api/tenants/{tenantId}/conversations</c>.</summary>
    private static async Task<IResult> ListAsync(
        Guid tenantId,
        int? page,
        int? pageSize,
        ReadConversationsHandler handler,
        CancellationToken cancellationToken)
    {
        ConversationPage? result = await handler
            .ListAsync(new ListConversationsQuery(tenantId, page, pageSize), cancellationToken)
            .ConfigureAwait(false);

        if (result is null)
        {
            return Results.NotFound();
        }

        return Results.Ok(
            new ConversationPageResponse(
                [.. result.Items.Select(item => new ConversationSummaryResponse(
                    item.Id,
                    item.Channel.ToString(),
                    item.Status.ToString(),
                    item.Handling.ToString(),
                    item.StartedAt,
                    item.LastActivityAt,
                    item.AiAgentName,
                    item.MessageCount,
                    item.LastMessagePreview,
                    item.LastMessageSender?.ToString(),
                    ToMember(item.AssignedTo)))],
                result.Page,
                result.PageSize,
                result.Total));
    }

    /// <summary><c>GET /api/tenants/{tenantId}/conversations/{conversationId}</c>.</summary>
    private static async Task<IResult> GetAsync(
        Guid tenantId,
        Guid conversationId,
        HttpContext http,
        ReadConversationsHandler handler,
        CancellationToken cancellationToken)
    {
        Versioned<ConversationDetail>? detail = await handler
            .GetAsync(new GetConversationQuery(tenantId, conversationId), cancellationToken)
            .ConfigureAwait(false);

        if (detail is null)
        {
            return Results.NotFound();
        }

        // The version a takeover or an assignment must present back. Emitted on
        // the read so the client never has to ask for it separately, and never
        // has to guess it.
        http.Response.Headers.ETag = EntityTags.Format(detail.Version);

        return Results.Ok(Describe(detail.Value));
    }

    /// <summary><c>GET /api/tenants/{tenantId}/conversations/{conversationId}/messages</c>.</summary>
    /// <remarks>
    /// Paged by ingestion sequence, never by time. A cursor of "after sequence N"
    /// stays correct while the conversation is still being added to, which a page
    /// number would not: a customer replying between two page reads would shift
    /// every subsequent offset.
    /// </remarks>
    private static async Task<IResult> ListMessagesAsync(
        Guid tenantId,
        Guid conversationId,
        long? after,
        int? limit,
        ReadConversationsHandler handler,
        CancellationToken cancellationToken)
    {
        ConversationMessagePage? page = await handler
            .ListMessagesAsync(
                new ListConversationMessagesQuery(tenantId, conversationId, after, limit),
                cancellationToken)
            .ConfigureAwait(false);

        if (page is null)
        {
            return Results.NotFound();
        }

        return Results.Ok(
            new TranscriptPageResponse(
                [.. page.Items.Select(message => new TranscriptMessageResponse(
                    message.Id,
                    message.Sender.ToString(),
                    message.Text,
                    message.SentAt,
                    message.IngestionSequence,
                    ToMember(message.SentBy)))],
                page.NextCursor));
    }

    /// <summary><c>POST .../conversations/{id}/take-over</c>.</summary>
    private static Task<IResult> TakeOverAsync(
        Guid tenantId,
        Guid conversationId,
        HttpContext http,
        ConversationHandoffHandler handler,
        ReadConversationsHandler reader,
        CancellationToken cancellationToken) =>
        SetHandlingAsync(
            tenantId,
            conversationId,
            toHuman: true,
            http,
            handler,
            reader,
            cancellationToken);

    /// <summary><c>POST .../conversations/{id}/return-to-ai</c>.</summary>
    private static Task<IResult> ReturnToAiAsync(
        Guid tenantId,
        Guid conversationId,
        HttpContext http,
        ConversationHandoffHandler handler,
        ReadConversationsHandler reader,
        CancellationToken cancellationToken) =>
        SetHandlingAsync(
            tenantId,
            conversationId,
            toHuman: false,
            http,
            handler,
            reader,
            cancellationToken);

    private static async Task<IResult> SetHandlingAsync(
        Guid tenantId,
        Guid conversationId,
        bool toHuman,
        HttpContext http,
        ConversationHandoffHandler handler,
        ReadConversationsHandler reader,
        CancellationToken cancellationToken)
    {
        // 428 without a precondition, 400 for a malformed one. Both before the
        // handler, so an unconditional write never reaches a use case that would
        // have performed it.
        if (EntityTags.ReadIfMatch(http.Request, out ConcurrencyToken expected) is IResult refusal)
        {
            return refusal;
        }

        Versioned<Conversation>? updated = await handler
            .HandleAsync(
                new SetConversationHandlingCommand(tenantId, conversationId, toHuman, expected),
                cancellationToken)
            .ConfigureAwait(false);

        return updated is null
            ? Results.NotFound()
            : await DescribeAsync(tenantId, conversationId, http, reader, cancellationToken)
                .ConfigureAwait(false);
    }

    /// <summary><c>PUT .../conversations/{id}/assignment</c>.</summary>
    /// <remarks>
    /// A <c>PUT</c> of the whole assignment rather than two verbs, because
    /// "assign to nobody" is a value of the same field and not a different
    /// operation. A null member unassigns.
    /// </remarks>
    private static async Task<IResult> AssignAsync(
        Guid tenantId,
        Guid conversationId,
        AssignConversationRequest? request,
        HttpContext http,
        ConversationAssignmentHandler handler,
        ReadConversationsHandler reader,
        CancellationToken cancellationToken)
    {
        if (EntityTags.ReadIfMatch(http.Request, out ConcurrencyToken expected) is IResult refusal)
        {
            return refusal;
        }

        Versioned<Conversation>? updated = await handler
            .AssignAsync(
                new AssignConversationCommand(tenantId, conversationId, request?.Member, expected),
                cancellationToken)
            .ConfigureAwait(false);

        return updated is null
            ? Results.NotFound()
            : await DescribeAsync(tenantId, conversationId, http, reader, cancellationToken)
                .ConfigureAwait(false);
    }

    /// <summary><c>POST .../conversations/{id}/messages</c>.</summary>
    /// <remarks>
    /// <strong>No <c>If-Match</c>, deliberately.</strong> A composer is a text box
    /// somebody has been typing in while the conversation moved underneath them —
    /// a customer wrote something, a colleague claimed it — and none of those
    /// changes makes the reply they typed wrong. Requiring a version here would
    /// reject correct replies for irrelevant reasons. What must not happen twice
    /// is the reply itself, and the idempotency key prevents exactly that.
    /// </remarks>
    private static async Task<IResult> ReplyAsync(
        Guid tenantId,
        Guid conversationId,
        ReplyToConversationRequest? request,
        ReplyToConversationHandler handler,
        CancellationToken cancellationToken)
    {
        ConversationMessageRecord? reply = await handler
            .HandleAsync(
                new ReplyToConversationCommand(
                    tenantId,
                    conversationId,
                    request?.ClientMessageId,
                    request?.Text),
                cancellationToken)
            .ConfigureAwait(false);

        return reply is null
            ? Results.NotFound()
            : Results.Ok(
                new TranscriptMessageResponse(
                    reply.Id,
                    reply.Sender.ToString(),
                    reply.Text,
                    reply.SentAt,
                    reply.IngestionSequence,
                    ToMember(reply.SentBy)));
    }

    /// <summary><c>GET .../conversations/assignees</c>.</summary>
    private static async Task<IResult> ListAssigneesAsync(
        Guid tenantId,
        ConversationAssignmentHandler handler,
        CancellationToken cancellationToken)
    {
        IReadOnlyList<ConversationMessageAuthor>? members = await handler
            .ListAssigneesAsync(new ListAssigneesQuery(tenantId), cancellationToken)
            .ConfigureAwait(false);

        return members is null
            ? Results.NotFound()
            : Results.Ok(members.Select(member => new WorkspaceMemberResponse(
                member.UserId,
                member.Email)));
    }

    /// <summary>
    /// Answers a mutation by reading the conversation back, with its new version.
    /// </summary>
    /// <remarks>
    /// <strong>Re-read rather than described from the aggregate that was just
    /// saved.</strong> The write path deliberately loads neither the agent's name
    /// nor the assignee's email — they are a join and a user lookup it has no
    /// other use for — so describing the saved aggregate would mean answering
    /// with those fields blank or, worse, inventing placeholders for them. A
    /// response that says a conversation is assigned to somebody with no name is
    /// a response a screen will render.
    /// <para>
    /// The cost is one extra query on an action a person performs by hand, which
    /// is the right place to spend one. The version comes from the same read, so
    /// the ETag and the body are the same revision by construction rather than by
    /// two values agreeing.
    /// </para>
    /// </remarks>
    private static async Task<IResult> DescribeAsync(
        Guid tenantId,
        Guid conversationId,
        HttpContext http,
        ReadConversationsHandler reader,
        CancellationToken cancellationToken)
    {
        Versioned<ConversationDetail>? detail = await reader
            .GetAsync(new GetConversationQuery(tenantId, conversationId), cancellationToken)
            .ConfigureAwait(false);

        if (detail is null)
        {
            return Results.NotFound();
        }

        http.Response.Headers.ETag = EntityTags.Format(detail.Version);

        return Results.Ok(Describe(detail.Value));
    }

    private static ConversationDetailResponse Describe(ConversationDetail detail) =>
        new(
            detail.Id,
            detail.Channel.ToString(),
            detail.Status.ToString(),
            detail.Handling.ToString(),
            detail.StartedAt,
            detail.LastActivityAt,
            detail.AiAgentName,
            detail.MessageCount,
            ToMember(detail.AssignedTo));

    private static WorkspaceMemberResponse? ToMember(ConversationMessageAuthor? author) =>
        author is null ? null : new WorkspaceMemberResponse(author.UserId, author.Email);
}
