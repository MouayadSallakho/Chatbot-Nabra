import { ComponentFixture, TestBed } from '@angular/core/testing';
import type { ChatMessage } from '@app/features/chat/hosted-chat-api';
import { ChatPanel } from './chat-panel';
import { waitAdvice } from './visitor-copy';

describe('ChatPanel', () => {
  let fixture: ComponentFixture<ChatPanel>;

  const message = (id: string, sender: ChatMessage['sender'], text: string): ChatMessage => ({
    id,
    sender,
    text,
    sentAt: '2026-10-19T10:00:00Z',
  });

  function mount(inputs: Record<string, unknown> = {}): void {
    fixture = TestBed.createComponent(ChatPanel);
    fixture.componentRef.setInput('agentName', 'Concierge');
    fixture.componentRef.setInput('canSend', true);

    for (const [name, value] of Object.entries(inputs)) {
      fixture.componentRef.setInput(name, value);
    }

    fixture.detectChanges();
  }

  const host = (): HTMLElement => fixture.nativeElement as HTMLElement;
  const rows = (): HTMLElement[] => [
    ...host().querySelectorAll<HTMLElement>('[data-testid="chat-message"]'),
  ];

  describe('the heading', () => {
    const title = (): string =>
      host().querySelector('[data-testid="chat-title"]')?.textContent?.trim() ?? '';

    it("is the workspace's name, isolated from the page's direction", () => {
      mount({ workspaceName: 'نورثويند' });

      expect(title()).toBe('نورثويند');
      expect(host().querySelector('[data-testid="chat-title"] bdi')).not.toBeNull();
    });

    it("is the agent's name where a page has no workspace name to give", () => {
      mount();

      expect(title()).toBe('Concierge');
    });

    it('keeps naming the agent on its replies', () => {
      mount({ workspaceName: 'Northwind', messages: [message('1', 'AiAgent', 'Hello.')] });

      expect(rows()[0].textContent).toContain('Concierge');
    });
  });

  describe('the glass header (Calm Glass, Phase 39.5b)', () => {
    const head = (): HTMLElement => host().querySelector('.chat-head') as HTMLElement;
    const status = (): HTMLElement | null => host().querySelector('[data-testid="chat-status"]');

    it("is a glass layer with the workspace's first letter on its tile", () => {
      mount({ workspaceName: 'northwind' });

      expect(head().classList).toContain('glass');
      expect(host().querySelector('.chat-tile')?.textContent?.trim()).toBe('N');
      expect(host().querySelector('.chat-tile')?.getAttribute('aria-hidden')).toBe('true');
    });

    it('takes a whole first character of an Arabic name', () => {
      mount({ workspaceName: 'نورثويند' });

      expect(host().querySelector('.chat-tile')?.textContent?.trim()).toBe('ن');
    });

    it("says only who answers: the agent's name, never how fast", () => {
      mount({ workspaceName: 'Northwind' });

      expect(status()?.textContent?.trim()).toBe('Concierge');
      expect(status()?.classList).not.toContain('is-off');
      expect(head().textContent).not.toMatch(/second|minute|replies in/i);
    });

    it('says "Unavailable", in words, when the chat cannot be used', () => {
      mount({ workspaceName: 'Northwind', state: 'unavailable' });

      expect(status()?.textContent?.trim()).toBe('Unavailable');
      expect(status()?.classList).toContain('is-off');
    });

    it("has no status line when the heading already is the agent's name", () => {
      mount();

      expect(status()).toBeNull();
    });
  });

  describe('the foot', () => {
    it('keeps the honesty line and says "Powered by Nabra", quietly and without a link', () => {
      mount({ workspaceName: 'Northwind' });

      const colophon = host().querySelector('.chat-colophon') as HTMLElement;

      expect(colophon.querySelector('.chat-honesty')?.textContent).toContain(
        'Answers are generated by AI.',
      );
      expect(colophon.querySelector('.chat-powered')?.textContent?.trim()).toBe('Powered by Nabra');
      expect(colophon.querySelector('a')).toBeNull();
    });

    it('still names who makes the chat when it is not available', () => {
      mount({ workspaceName: 'Northwind', state: 'unavailable' });

      expect(host().querySelector('.chat-powered')).not.toBeNull();
      expect(host().querySelector('.chat-honesty')).toBeNull();
      expect(host().querySelector('[data-testid="chat-input"]')).toBeNull();
    });

    it('is a glass pill with a round Send named in words, its arrow drawn', () => {
      mount();

      const composer = host().querySelector('.chat-composer') as HTMLElement;
      const send = host().querySelector<HTMLButtonElement>('[data-testid="chat-send"]')!;

      expect(composer.classList).toContain('glass');
      expect(send.textContent?.trim()).toBe('Send');
      expect(send.querySelector('.visually-hidden')?.textContent?.trim()).toBe('Send');
      expect(send.querySelector('app-icon')?.classList).toContain('mirrors');
    });

    it('says "Sending…" on the button while a message is on its way', () => {
      mount({ sending: true });

      expect(host().querySelector('[data-testid="chat-send"]')?.textContent?.trim()).toBe(
        'Sending…',
      );
    });
  });

  it('tells the three speakers apart by place, marker and word, never by colour alone', () => {
    mount({
      messages: [
        message('1', 'Customer', 'Where is my order?'),
        message('2', 'AiAgent', 'Let me check.'),
        message('3', 'HumanAgent', 'It ships today.'),
      ],
    });

    const [mine, ai, person] = rows();

    expect(mine.classList).toContain('chat-msg-mine');
    expect(mine.textContent).toContain('You:');
    expect(ai.classList).toContain('chat-msg-ai');
    expect(ai.querySelector('.chat-sender')?.textContent).toContain('Concierge');
    expect(person.classList).toContain('chat-msg-person');
    expect(person.querySelector('.chat-sender')?.textContent).toContain('Support');
    expect(person.querySelector('app-icon')).not.toBeNull();

    // The three voices (Phase 39.5a): the visitor's own words in a bubble with
    // no mark; the AI beside the orb; a person beside the gold person mark.
    expect(mine.querySelector('.chat-bubble')?.classList).not.toContain('bubble-ai');
    expect(mine.querySelector('app-orb, .chat-mark')).toBeNull();
    expect(ai.querySelector('.chat-bubble')?.classList).toContain('bubble-ai');
    expect(ai.querySelector('app-orb')?.getAttribute('aria-hidden')).toBe('true');
    expect(ai.querySelector('app-orb')?.classList).not.toContain('is-thinking');
    expect(person.querySelector('.chat-bubble')?.classList).toContain('bubble-team');
    expect(person.querySelector('.chat-mark-team')?.getAttribute('aria-hidden')).toBe('true');
    // The mark comes first in reading order, so it sits on the start side and
    // mirrors with the page.
    expect(ai.firstElementChild?.tagName.toLowerCase()).toBe('app-orb');
    expect(person.firstElementChild?.classList).toContain('chat-mark-team');
    // Never a member's name for a visitor (owner decision Q5).
    expect(person.textContent?.replace(/\s+/g, ' ').trim()).toBe('Support It ships today.');

    // Every message keeps its own direction.
    for (const row of rows()) {
      expect(row.querySelector('.chat-text')?.getAttribute('dir')).toBe('auto');
    }
  });

  it('draws a handoff line only where the replying voice really changes', () => {
    mount({
      messages: [
        message('1', 'Customer', 'Hi'),
        message('2', 'AiAgent', 'Hello'),
        message('3', 'Customer', 'A person please'),
        message('4', 'HumanAgent', 'I am here'),
        message('5', 'HumanAgent', 'Anything else?'),
        message('6', 'AiAgent', 'Back with you'),
      ],
    });

    const dividers = [...host().querySelectorAll('[data-testid="chat-handoff-divider"]')];

    expect(dividers.map((divider) => divider.textContent?.trim())).toEqual([
      'A person from the support team joined',
      'Concierge is answering again',
    ]);
  });

  it('shows the typing state for the AI only, and the handoff notice for a person', () => {
    mount({ sending: true, handling: 'Ai' });

    expect(host().querySelector('[data-testid="chat-typing"]')?.textContent).toContain(
      'Concierge is typing',
    );
    // The orb breathes beside the dots while the AI answers; the words say it.
    expect(
      host()
        .querySelector('[data-testid="chat-typing"] app-orb')
        ?.classList.contains('is-thinking'),
    ).toBe(true);
    expect(host().querySelector('[data-testid="chat-handover"]')).toBeNull();

    fixture.componentRef.setInput('handling', 'Human');
    fixture.detectChanges();

    expect(host().querySelector('[data-testid="chat-typing"]')).toBeNull();
    expect(host().querySelector('[data-testid="chat-handover"]')?.textContent).toContain(
      'A support team member will reply here.',
    );
  });

  it('opens with the orb above the greeting, apart from the transcript', () => {
    mount({ greeting: 'Ask us about orders.' });

    const greeting = host().querySelector('[data-testid="chat-greeting"]');
    const intro = greeting?.closest('.chat-intro');

    expect(greeting?.textContent).toContain('Ask us about orders.');
    expect(greeting?.getAttribute('dir')).toBe('auto');
    expect(greeting?.closest('.chat-msg')).toBeNull();
    expect(intro?.querySelector('app-orb.orb-lg')).not.toBeNull();
  });

  it('puts the orb above an invitation when there is no greeting and nothing said yet', () => {
    mount();

    const empty = host().querySelector('[data-testid="chat-empty"]');

    expect(empty?.textContent).toContain('Ask anything to start the conversation.');
    expect(empty?.closest('.chat-intro')?.querySelector('app-orb')).not.toBeNull();
  });

  it('sends on Enter and on the button, keeps Shift+Enter for a new line, and ignores an empty box', () => {
    mount();

    const sent = vi.fn();

    fixture.componentInstance.send.subscribe(sent);

    const box = host().querySelector<HTMLTextAreaElement>('[data-testid="chat-input"]')!;

    box.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter' }));
    expect(sent).not.toHaveBeenCalled();

    box.value = 'Hello';
    box.dispatchEvent(new Event('input'));
    box.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', shiftKey: true }));
    expect(sent).not.toHaveBeenCalled();
    expect(fixture.componentInstance.draft()).toBe('Hello');

    box.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter' }));
    expect(sent).toHaveBeenCalledTimes(1);

    host().querySelector<HTMLButtonElement>('[data-testid="chat-send"]')!.click();
    expect(sent).toHaveBeenCalledTimes(2);
  });

  it('sends nothing from a preview, and gives it no heading', () => {
    mount({ preview: true, titleIsHeading: false });

    const sent = vi.fn();

    fixture.componentInstance.send.subscribe(sent);
    fixture.componentInstance.draft.set('Hello');
    fixture.detectChanges();

    host().querySelector<HTMLButtonElement>('[data-testid="chat-send"]')!.click();

    expect(sent).not.toHaveBeenCalled();
    expect(host().querySelector('h1')).toBeNull();
  });

  it('says a missing answer as an error to a visitor, and as information only where asked', () => {
    const failure = {
      kind: 'providerUnavailable',
      status: 503,
      message: 'Sorry, no answer came back just now.',
    };

    mount({ failure });

    const alert = (): Element => host().querySelector('[data-testid="chat-error"]')!;

    expect(alert().classList).toContain('alert-danger');

    fixture.componentRef.setInput('infoKinds', ['providerUnavailable']);
    fixture.detectChanges();

    expect(alert().classList).toContain('alert-info');
    expect(alert().classList).not.toContain('alert-danger');

    // A wait is a warning whatever the host asked.
    fixture.componentRef.setInput('failure', { ...failure, kind: 'rateLimited', status: 429 });
    fixture.detectChanges();

    expect(alert().classList).toContain('alert-warning');
  });

  it('renders markup a visitor typed as text', () => {
    mount({ messages: [message('1', 'Customer', '<img src=x onerror=alert(1)><b>bold</b>')] });

    expect(host().querySelector('[data-testid="chat-transcript"] img')).toBeNull();
    expect(host().querySelector('[data-testid="chat-transcript"] b')).toBeNull();
    expect(rows()[0].textContent).toContain('<b>bold</b>');
  });
});

describe('waitAdvice', () => {
  it('says the honest vague thing without a usable wait', () => {
    for (const seconds of [undefined, 0, -3, Number.NaN]) {
      expect(waitAdvice(seconds, 'en')).toBe('Please wait a moment and try again.');
    }
  });

  it('counts seconds up to a minute and a half, then whole minutes', () => {
    expect(waitAdvice(1, 'en')).toBe('Please wait about 1 second and try again.');
    expect(waitAdvice(30, 'en')).toBe('Please wait about 30 seconds and try again.');
    expect(waitAdvice(150, 'en')).toBe('Please wait about 3 minutes and try again.');
  });
});
