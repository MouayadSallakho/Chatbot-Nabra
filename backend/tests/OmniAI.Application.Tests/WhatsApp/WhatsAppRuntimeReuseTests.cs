using OmniAI.Application.Ai;
using OmniAI.Application.Tests.WebChat;
using OmniAI.Application.WhatsApp;
using OmniAI.Application.WhatsApp.Persistence;
using OmniAI.Domain.Conversations;
using OmniAI.Domain.Customers;
using OmniAI.Domain.WhatsApp;
using OmniAI.Testing;

namespace OmniAI.Application.Tests.WhatsApp;

/// <summary>
/// WhatsApp entering the conversation runtime website chat already uses.
/// </summary>
/// <remarks>
/// <strong>These tests drive the same <c>CustomerTurnRunner</c> instance the
/// website chat suite drives.</strong> That is the point of the phase: there is
/// one place where a customer's message is locked, replayed, answered or handed
/// to a person, and WhatsApp is a transport in front of it rather than a second
/// copy of it. If somebody reintroduced a WhatsApp-specific runtime, these tests
/// would keep passing only by being rewritten to build it.
/// </remarks>
public sealed class WhatsAppRuntimeReuseTests
{
    private const string ConnectedNumber = "100200300400500";

    [Fact]
    public async Task An_inbound_message_is_answered_by_the_shared_runtime_and_queued_once()
    {
        Scenario scenario = Scenario.Build();

        await scenario.ProcessAsync("wamid.FIRST==", "What are your opening hours?");

        // One reply generated by the shared runner, and one delivery queued
        // beside it. The AI never sends: it stores, and a worker delivers.
        Assert.Equal(1, scenario.Harness.Generator.Calls);

        WhatsAppDelivery delivery = Assert.Single(scenario.WhatsApp.Deliveries);

        Assert.Equal(WhatsAppDeliveryStatus.Pending, delivery.Status);
        Assert.Equal(scenario.Conversation.Id, delivery.ConversationId);
    }

    [Fact]
    public async Task An_inbound_turn_uses_the_same_persisted_key_as_existing_WhatsApp_conversations()
    {
        Scenario scenario = Scenario.Build();
        await scenario.ProcessAsync("wamid.LEGACY==", "Hello");

        var existingKey = ClientMessageId.Create("wa-8be6bff213187dac513c4369004d267931d84368");
        Assert.NotNull(await scenario.Harness.World.FindTurnAsync(scenario.Conversation.Id, existingKey));
    }

    [Fact]
    public async Task A_redelivered_message_is_replayed_and_never_answered_twice()
    {
        Scenario scenario = Scenario.Build();

        await scenario.ProcessAsync("wamid.REPEAT==", "Hello");
        await scenario.ProcessAsync("wamid.REPEAT==", "Hello");

        // <strong>The whole of inbound idempotency, end to end.</strong> The same
        // provider message id maps to the same client message id, the runner
        // replays the settled turn, and nothing is generated or queued again.
        Assert.Equal(1, scenario.Harness.Generator.Calls);
        Assert.Single(scenario.WhatsApp.Deliveries);
    }

    [Fact]
    public async Task In_human_mode_the_message_is_kept_and_nothing_is_generated_or_sent()
    {
        Scenario scenario = Scenario.Build();

        scenario.Harness.World.Handling = ConversationHandling.Human;

        await scenario.ProcessAsync("wamid.HUMAN==", "Is anyone there?");

        // Phase 19's rule, unchanged by the new channel: a customer writing to a
        // conversation a person has taken over costs nothing. No generation, no
        // embedding, no delivery -- and the message is still stored, because the
        // colleague has to be able to read it.
        Assert.Equal(0, scenario.Harness.Generator.Calls);
        Assert.Equal(0, scenario.Harness.Embeddings.Calls);
        Assert.Empty(scenario.WhatsApp.Deliveries);
        Assert.Equal(1, scenario.Harness.World.SettledWithoutReply);

        // And the inbox was told, so the reply appears on a colleague's screen
        // without them reloading.
        Assert.NotEmpty(scenario.Harness.Announcer.Announced);
    }

    [Fact]
    public async Task A_message_on_a_connection_that_was_switched_off_is_not_answered()
    {
        Scenario scenario = Scenario.Build();

        // Claimed while the channel was live, reached after somebody disabled it.
        // Routing is re-read in the worker precisely for this.
        ClaimedInboundMessage claimed = await scenario.ClaimAsync(
            "wamid.LATE==",
            "Still there?");

        scenario.Connection.Disable(Scenario.Noon);

        await scenario.Processor.HandleAsync(claimed);

        Assert.Equal(0, scenario.Harness.Generator.Calls);
        Assert.Empty(scenario.WhatsApp.Deliveries);
    }

    [Fact]
    public async Task A_failed_reply_is_announced_so_the_inbox_shows_the_message()
    {
        // The same rule as website chat, through the same runner: the
        // customer's words are stored before the provider is called, so the
        // inbox is told even when no reply exists to send. Twice since Phase
        // 38.7a: when the message is stored, and when the turn has failed.
        Scenario scenario = Scenario.Build(
            RecordingGenerator.Failing(() => new AiRuntimeUnavailableException()));

        ClaimedInboundMessage claimed = await scenario.ClaimAsync(
            "wamid.FAILED==",
            "Is the shop open today?");

        int before = scenario.Harness.Announcer.Announced.Count(
            announced => announced.Conversation == scenario.Conversation.Id);

        await Assert.ThrowsAsync<AiRuntimeUnavailableException>(
            () => scenario.Processor.HandleAsync(claimed));

        Assert.Equal(
            before + 2,
            scenario.Harness.Announcer.Announced.Count(
                announced => announced.Conversation == scenario.Conversation.Id));

        // Nothing to deliver, because nothing was generated.
        Assert.Empty(scenario.WhatsApp.Deliveries);
    }

    private sealed class Scenario
    {
        public static readonly DateTimeOffset Noon = Harness.Noon;

        public required Harness Harness { get; init; }

        public required WhatsAppWorld WhatsApp { get; init; }

        public required WhatsAppConnection Connection { get; init; }

        public required Conversation Conversation { get; init; }

        public required ProcessInboundWhatsAppHandler Processor { get; init; }

        public required ReceiveWhatsAppWebhookHandler Webhook { get; init; }

        public static Scenario Build(RecordingGenerator? generator = null)
        {
            Harness harness = Harness.Build(generator);

            WhatsAppWorld whatsapp = new();

            WhatsAppConnection connection = whatsapp.Serving(
                harness.Workspace,
                harness.Agent.Id,
                ConnectedNumber,
                Noon);

            // One conversation, known to both halves of the scenario: the
            // WhatsApp mapping hands out its id, and the runtime can find it.
            Conversation conversation = Conversation.Start(
                harness.Workspace,
                CustomerId.New(),
                ChannelKind.WhatsApp,
                Noon);

            harness.World.AddConversation(conversation);
            whatsapp.NextConversation = () => conversation.Id;

            FixedTimeProvider clock = new(Noon);

            return new Scenario
            {
                Harness = harness,
                WhatsApp = whatsapp,
                Connection = connection,
                Conversation = conversation,
                Processor = new ProcessInboundWhatsAppHandler(
                    whatsapp,
                    whatsapp,
                    whatsapp,
                    harness.Agents,
                    harness.Runner,
                    clock),
                Webhook = new ReceiveWhatsAppWebhookHandler(
                    whatsapp,
                    whatsapp,
                    whatsapp,
                    harness.Announcer,
                    clock),
            };
        }

        /// <summary>Takes one message through the webhook, the inbox and the worker.</summary>
        public async Task ProcessAsync(string providerMessageId, string text)
        {
            ClaimedInboundMessage? claimed = await TryClaimAsync(providerMessageId, text);

            if (claimed is not null)
            {
                await Processor.HandleAsync(claimed);
            }
        }

        public async Task<ClaimedInboundMessage> ClaimAsync(string providerMessageId, string text) =>
            await TryClaimAsync(providerMessageId, text)
            ?? throw new InvalidOperationException("Nothing was claimed.");

        private async Task<ClaimedInboundMessage?> TryClaimAsync(
            string providerMessageId,
            string text)
        {
            await Webhook.HandleAsync(new WhatsAppWebhook(
                [
                    new InboundWebhookMessage(
                        ConnectedNumber,
                        providerMessageId,
                        "447700900123",
                        "text",
                        text,
                        Noon),
                ],
                []));

            IReadOnlyList<ClaimedInboundMessage> claimed =
                await WhatsApp.ClaimInboundAsync(now: Noon);

            return claimed.Count == 0 ? null : claimed[0];
        }
    }
}
