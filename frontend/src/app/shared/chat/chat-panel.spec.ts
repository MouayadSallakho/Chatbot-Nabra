import { ComponentFixture, TestBed } from '@angular/core/testing';
import type { ChatMessage } from '@app/features/chat/hosted-chat-api';
import { ChatPanel } from './chat-panel';
import { waitAdvice } from './visitor-copy';

describe('ChatPanel', () => {
  let fixture: ComponentFixture<ChatPanel>;

  const message = (id: string, sender: ChatMessage['sender'], text: string): ChatMessage => ({
    id,
    sender,
    text,
    sentAt: '2026-10-19T10:00:00Z',
  });

  function mount(inputs: Record<string, unknown> = {}): void {
    fixture = TestBed.createComponent(ChatPanel);
    fixture.componentRef.setInput('agentName', 'Concierge');
    fixture.componentRef.setInput('canSend', true);

    for (const [name, value] of Object.entries(inputs)) {
      fixture.componentRef.setInput(name, value);
    }

    fixture.detectChanges();
  }

  const host = (): HTMLElement => fixture.nativeElement as HTMLElement;
  const rows = (): HTMLElement[] => [
    ...host().querySelectorAll<HTMLElement>('[data-testid="chat-message"]'),
  ];

  it('tells the three speakers apart by place, marker and word, never by colour alone', () => {
    mount({
      messages: [
        message('1', 'Customer', 'Where is my order?'),
        message('2', 'AiAgent', 'Let me check.'),
        message('3', 'HumanAgent', 'It ships today.'),
      ],
    });

    const [mine, ai, person] = rows();

    expect(mine.classList).toContain('chat-msg-mine');
    expect(mine.textContent).toContain('You:');
    expect(ai.classList).toContain('chat-msg-ai');
    expect(ai.querySelector('.chat-sender')?.textContent).toContain('Concierge');
    expect(person.classList).toContain('chat-msg-person');
    expect(person.querySelector('.chat-sender')?.textContent).toContain('Support');
    expect(person.querySelector('app-icon')).not.toBeNull();

    // Every message keeps its own direction.
    for (const row of rows()) {
      expect(row.querySelector('.chat-text')?.getAttribute('dir')).toBe('auto');
    }
  });

  it('draws a handoff line only where the replying voice really changes', () => {
    mount({
      messages: [
        message('1', 'Customer', 'Hi'),
        message('2', 'AiAgent', 'Hello'),
        message('3', 'Customer', 'A person please'),
        message('4', 'HumanAgent', 'I am here'),
        message('5', 'HumanAgent', 'Anything else?'),
        message('6', 'AiAgent', 'Back with you'),
      ],
    });

    const dividers = [...host().querySelectorAll('[data-testid="chat-handoff-divider"]')];

    expect(dividers.map((divider) => divider.textContent?.trim())).toEqual([
      'A person from the support team joined',
      'Concierge is answering again',
    ]);
  });

  it('shows the typing state for the AI only, and the handoff notice for a person', () => {
    mount({ sending: true, handling: 'Ai' });

    expect(host().querySelector('[data-testid="chat-typing"]')?.textContent).toContain(
      'Concierge is typing',
    );
    expect(host().querySelector('[data-testid="chat-handover"]')).toBeNull();

    fixture.componentRef.setInput('handling', 'Human');
    fixture.detectChanges();

    expect(host().querySelector('[data-testid="chat-typing"]')).toBeNull();
    expect(host().querySelector('[data-testid="chat-handover"]')?.textContent).toContain(
      'A support team member will reply here.',
    );
  });

  it('keeps the greeting apart from the transcript, and the honesty line in the header', () => {
    mount({ greeting: 'Ask us about orders.' });

    const greeting = host().querySelector('[data-testid="chat-greeting"]');

    expect(greeting?.textContent).toContain('Ask us about orders.');
    expect(greeting?.classList).not.toContain('chat-msg');
    expect(host().querySelector('.chat-head')?.textContent).toContain(
      'Answers are generated by AI.',
    );
  });

  it('sends on Enter and on the button, keeps Shift+Enter for a new line, and ignores an empty box', () => {
    mount();

    const sent = vi.fn();

    fixture.componentInstance.send.subscribe(sent);

    const box = host().querySelector<HTMLTextAreaElement>('[data-testid="chat-input"]')!;

    box.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter' }));
    expect(sent).not.toHaveBeenCalled();

    box.value = 'Hello';
    box.dispatchEvent(new Event('input'));
    box.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', shiftKey: true }));
    expect(sent).not.toHaveBeenCalled();
    expect(fixture.componentInstance.draft()).toBe('Hello');

    box.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter' }));
    expect(sent).toHaveBeenCalledTimes(1);

    host().querySelector<HTMLButtonElement>('[data-testid="chat-send"]')!.click();
    expect(sent).toHaveBeenCalledTimes(2);
  });

  it('sends nothing from a preview, and gives it no heading', () => {
    mount({ preview: true, titleIsHeading: false });

    const sent = vi.fn();

    fixture.componentInstance.send.subscribe(sent);
    fixture.componentInstance.draft.set('Hello');
    fixture.detectChanges();

    host().querySelector<HTMLButtonElement>('[data-testid="chat-send"]')!.click();

    expect(sent).not.toHaveBeenCalled();
    expect(host().querySelector('h1')).toBeNull();
  });

  it('says a missing answer as an error to a visitor, and as information only where asked', () => {
    const failure = {
      kind: 'providerUnavailable',
      status: 503,
      message: 'Sorry, no answer came back just now.',
    };

    mount({ failure });

    const alert = (): Element => host().querySelector('[data-testid="chat-error"]')!;

    expect(alert().classList).toContain('alert-danger');

    fixture.componentRef.setInput('infoKinds', ['providerUnavailable']);
    fixture.detectChanges();

    expect(alert().classList).toContain('alert-info');
    expect(alert().classList).not.toContain('alert-danger');

    // A wait is a warning whatever the host asked.
    fixture.componentRef.setInput('failure', { ...failure, kind: 'rateLimited', status: 429 });
    fixture.detectChanges();

    expect(alert().classList).toContain('alert-warning');
  });

  it('renders markup a visitor typed as text', () => {
    mount({ messages: [message('1', 'Customer', '<img src=x onerror=alert(1)><b>bold</b>')] });

    expect(host().querySelector('[data-testid="chat-transcript"] img')).toBeNull();
    expect(host().querySelector('[data-testid="chat-transcript"] b')).toBeNull();
    expect(rows()[0].textContent).toContain('<b>bold</b>');
  });
});

describe('waitAdvice', () => {
  it('says the honest vague thing without a usable wait', () => {
    for (const seconds of [undefined, 0, -3, Number.NaN]) {
      expect(waitAdvice(seconds, 'en')).toBe('Please wait a moment and try again.');
    }
  });

  it('counts seconds up to a minute and a half, then whole minutes', () => {
    expect(waitAdvice(1, 'en')).toBe('Please wait about 1 second and try again.');
    expect(waitAdvice(30, 'en')).toBe('Please wait about 30 seconds and try again.');
    expect(waitAdvice(150, 'en')).toBe('Please wait about 3 minutes and try again.');
  });
});
